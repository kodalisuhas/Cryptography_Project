"""Command-line argument parsing for the Cryptography Testing Lab CLI.

Standard-library ``argparse`` only. Defines the V1 subcommand surface
(``encrypt``, ``decrypt``, ``benchmark``, ``security``, ``menu``) and the
approved optional ``--verbose`` flag. AES is the only exposed V1 algorithm.
"""

import argparse

PROG = "crypto-lab"
DESCRIPTION = "Cryptography Testing Lab - AES encryption, benchmarking, and security analysis (V1)."

ALGORITHMS = ("AES",)
KEY_SIZES = (128, 192, 256)          # AES key sizes in bits
MODES = ("ECB", "CBC")              # asymmetric modes only in V1
INPUT_FORMATS = ("text", "hex")

DEFAULT_BENCHMARK_KEY_SIZES = "128,192,256"
DEFAULT_BENCHMARK_MODES = "ECB,CBC"
DEFAULT_BENCHMARK_PAYLOAD_SIZES = "1048576"


def _add_verbose(parser: argparse.ArgumentParser, *, suppress_default: bool = False) -> None:
    """Add the approved optional global verbose flag.

    The main parser declares the canonical default (``False``).  Each
    subparser declares the flag with ``default=SUPPRESS`` so that an
    ``--verbose`` given *before* the subcommand is not overwritten by the
    subparser's defaults (a Python 3.13 subparser-namespace quirk: the
    subparser namespace is merged back over the top-level one).
    """
    parser.add_argument(
        "--verbose",
        action="store_true",
        default=argparse.SUPPRESS if suppress_default else False,
        dest="verbose",
        help="Enable verbose/debug output (no new dependencies).",
    )


def _add_algorithm_arg(sub: argparse.ArgumentParser) -> None:
    sub.add_argument(
        "--algorithm",
        choices=ALGORITHMS,
        default="AES",
        help="Cipher algorithm (only AES exists in V1).",
    )


def _add_key_size_arg(sub: argparse.ArgumentParser) -> None:
    sub.add_argument(
        "--key-size",
        type=int,
        choices=KEY_SIZES,
        required=True,
        help="AES key size in bits (128, 192, or 256).",
    )


def _add_mode_arg(sub: argparse.ArgumentParser) -> None:
    sub.add_argument(
        "--mode",
        choices=MODES,
        required=True,
        help="Block cipher mode (ECB or CBC).",
    )


def _add_subparser(subparsers, name: str, **parser_kwargs):
    """Create a subparser with exact flag matching (no argparse abbreviation).

    ``allow_abbrev=False`` ensures, e.g., ``--key-size`` is never silently
    accepted as an abbreviation of ``--key-sizes`` on ``benchmark`` — every
    option must be spelled exactly.
    """
    return subparsers.add_parser(name, allow_abbrev=False, **parser_kwargs)


def create_parser() -> argparse.ArgumentParser:
    """Build the top-level parser with subcommands and help."""
    parser = argparse.ArgumentParser(
        prog=PROG,
        description=DESCRIPTION,
        allow_abbrev=False,
    )
    # Global --verbose (works both before and after the subcommand; see
    # _add_verbose for why subparsers use SUPPRESS).
    _add_verbose(parser)
    subparsers = parser.add_subparsers(
        dest="command",
        required=True,
        metavar="COMMAND",
        help="Available commands: encrypt, decrypt, benchmark, security, menu",
    )

    # --- encrypt -----------------------------------------------------------
    enc = _add_subparser(
        subparsers,
        "encrypt",
        help="Encrypt plaintext with AES (in memory).",
        description="Encrypt plaintext with AES. Key may be explicit hex, generated, or masked.",
    )
    _add_verbose(enc, suppress_default=True)
    _add_algorithm_arg(enc)
    _add_key_size_arg(enc)
    _add_mode_arg(enc)
    key_group = enc.add_mutually_exclusive_group()
    key_group.add_argument(
        "--key",
        metavar="HEX",
        help="AES key as hex. NOTE: command-line keys are visible to shell history / process listing.",
    )
    key_group.add_argument(
        "--generate-key",
        action="store_true",
        help="Generate a random key via Core and print it in hex for later decryption.",
    )
    enc.add_argument(
        "--input",
        required=False,
        help="Plaintext: text or hex (see --input-format).",
    )
    enc.add_argument(
        "--input-format",
        choices=INPUT_FORMATS,
        default="text",
        help="Interpretation of --input (default: text).",
    )
    enc.add_argument(
        "--iv",
        metavar="HEX",
        help="CBC IV as hex (optional; auto-generated by Core when omitted). ECB never takes an IV.",
    )
    enc.add_argument(
        "--input-file",
        metavar="PATH",
        help="Path to a binary file whose contents are the plaintext.",
    )
    enc.add_argument(
        "--output-file",
        metavar="PATH",
        help="Path to write the ciphertext file. CBC also writes a .iv sidecar.",
    )
    enc.add_argument(
        "--force",
        action="store_true",
        help="Overwrite --output-file if it already exists.",
    )

    # --- decrypt -----------------------------------------------------------
    dec = _add_subparser(
        subparsers,
        "decrypt",
        help="Decrypt AES ciphertext (in memory).",
        description="Decrypt AES ciphertext (hex input). CBC requires the matching IV.",
    )
    _add_verbose(dec, suppress_default=True)
    _add_algorithm_arg(dec)
    _add_key_size_arg(dec)
    _add_mode_arg(dec)
    dec.add_argument(
        "--key",
        metavar="HEX",
        required=True,
        help="AES key as hex.",
    )
    dec.add_argument(
        "--input",
        required=False,
        help="Ciphertext as hex.",
    )
    dec.add_argument(
        "--iv",
        metavar="HEX",
        help="CBC IV as hex (required for CBC decryption).",
    )
    dec.add_argument(
        "--input-file",
        metavar="PATH",
        help="Path to a ciphertext file to decrypt.",
    )
    dec.add_argument(
        "--output-file",
        metavar="PATH",
        help="Path to write the decrypted plaintext file.",
    )
    dec.add_argument(
        "--force",
        action="store_true",
        help="Overwrite --output-file if it already exists.",
    )

    # --- benchmark ---------------------------------------------------------
    bench = _add_subparser(
        subparsers,
        "benchmark",
        help="Run the frozen performance benchmark.",
        description=(
            "Run the frozen 5-warmup / 30-measured AES benchmark. The CLI selects "
            "configurations and payloads only; it never overrides iteration counts."
        ),
    )
    _add_verbose(bench, suppress_default=True)
    _add_algorithm_arg(bench)
    bench.add_argument(
        "--key-sizes",
        default=DEFAULT_BENCHMARK_KEY_SIZES,
        metavar="LIST",
        help="Comma-separated AES key sizes (default: 128,192,256).",
    )
    bench.add_argument(
        "--modes",
        default=DEFAULT_BENCHMARK_MODES,
        metavar="LIST",
        help="Comma-separated modes ECB/CBC (default: ECB,CBC).",
    )
    bench.add_argument(
        "--payload-sizes",
        default=DEFAULT_BENCHMARK_PAYLOAD_SIZES,
        metavar="LIST",
        help="Comma-separated payload sizes in bytes (default: 1048576 = 1 binary MiB).",
    )
    bench.add_argument(
        "--save-csv",
        metavar="DIR",
        help="Directory to save summary and raw benchmark CSVs.",
    )
    bench.add_argument(
        "--save-graphs",
        metavar="DIR",
        help="Directory to save benchmark graph PNGs.",
    )

    # --- security ----------------------------------------------------------
    sec = _add_subparser(
        subparsers,
        "security",
        help="Run the AES security analysis suite.",
        description=(
            "Run avalanche-effect, key-sensitivity, and ECB-weakness analysis via the frozen "
            "SecurityService. The CLI constructs the experiment inputs (1-bit pairs, BMP, IV)."
        ),
    )
    _add_verbose(sec, suppress_default=True)
    _add_algorithm_arg(sec)
    _add_mode_arg(sec)
    sec.add_argument(
        "--key",
        metavar="HEX",
        required=True,
        help="Base AES key (key1) as hex; its length selects the AES key size.",
    )
    sec.add_argument(
        "--plaintext",
        default="",
        help="Base plaintext (plaintext1): text or hex (see --plaintext-format). Empty = default sample.",
    )
    sec.add_argument(
        "--plaintext-format",
        choices=INPUT_FORMATS,
        default="text",
        help="Interpretation of --plaintext (default: text).",
    )
    sec.add_argument(
        "--iv",
        metavar="HEX",
        help="16-byte IV hex for the security suite (generated via Core when omitted).",
    )
    sec.add_argument(
        "--bmp-width",
        type=int,
        default=64,
        help="Width of the in-memory 24-bpp BMP used for the ECB weakness demo (default: 64).",
    )
    sec.add_argument(
        "--bmp-height",
        type=int,
        default=64,
        help="Height of the in-memory 24-bpp BMP used for the ECB weakness demo (default: 64).",
    )
    sec.add_argument(
        "--save-report",
        metavar="DIR",
        help="Directory to save the security analysis JSON report.",
    )

    # --- menu --------------------------------------------------------------
    menu_p = _add_subparser(
        subparsers,
        "menu",
        help="Launch the interactive menu (reuses the same command handlers).",
        description="Interactive guide to encrypt, decrypt, benchmark, and security.",
    )
    _add_verbose(menu_p, suppress_default=True)

    return parser


def validate_persistence_args(parser: argparse.ArgumentParser, args) -> None:
    """Validate the conditional input rule for encrypt/decrypt persistence.

    The frozen contract requires exactly one of ``--input`` or ``--input-file``
    for ``encrypt`` and ``decrypt``.  Argparse cannot express this conditional
    requirement, so it is enforced here, after parsing and before dispatch,
    using the parser's own error mechanism so invalid usage reports as an
    argparse-style usage error (exit code 2).

    Parameters
    ----------
    parser : argparse.ArgumentParser
        The parser that produced *args*, used to emit argparse-style errors.
    args
        The parsed namespace from ``parser.parse_args()``.
    """
    if args.command not in ("encrypt", "decrypt"):
        return
    has_input = args.input is not None
    has_input_file = getattr(args, "input_file", None) is not None
    both = has_input and has_input_file
    neither = not has_input and not has_input_file
    if both:
        parser.error(
            "argument conflict: --input and --input-file are mutually exclusive"
        )
    if neither:
        parser.error(
            "one of the following arguments is required: --input, --input-file"
        )